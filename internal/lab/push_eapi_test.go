// sessionDiff is cEOS's diff entry for a session that differs from running by a
// description: the device's words, and configuration, which nothing but the push's result
// may carry.
const sessionDiff = "--- system:/running-config\n" +
	"+++ session:/fylgja-1-session-config\n" +
	"+interface Ethernet1\n" +
	"+   description to n2 Ethernet1\n"

// eapiRanWithDiff answers as cEOS answers a replace under format text: one
// {"output": …} entry per command, the diff command's carrying diff.
func eapiRanWithDiff(diff string) func(http.ResponseWriter, *http.Request, []string) {
	return func(w http.ResponseWriter, _ *http.Request, cmds []string) {
		result := make([]map[string]any, len(cmds))
		for i, c := range cmds {
			result[i] = map[string]any{"output": ""}
			if c == cmdSessionDiff {
				result[i] = map[string]any{"output": diff}
			}
			if c == cmdCopyStartup {
				result[i]["messages"] = []string{"Copy completed successfully."}
			}
		}
		_ = json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "result": result})
	}
}

// The shipped package's push (M11 D-033): one request, answered as text,
// of privileged mode, the session, `rollback clean-config` and `copy startup-config
// session-config`, the bootstrap's lines whatever bootstrap_via says, the
// artifact's, `show session-config diffs` and `commit`. The result carries the diff
// entry's output, "" when the session equals running, and the log its length alone.
func TestPushEAPIReplaceInOneRequest(t *testing.T) {
	for _, c := range []struct {
		via, diff string
	}{
		{psp.BootstrapViaPush, sessionDiff},
		{psp.BootstrapViaStartupConfig, sessionDiff},
		{psp.BootstrapViaPush, ""},
	} {
		t.Run(fmt.Sprintf("%s/diff %d bytes", c.via, len(c.diff)), func(t *testing.T) {
			node := &eapiNode{answer: eapiRanWithDiff(c.diff)}
			a, in, log := eapiSetup(t, node, c.via)
			in.Push.Mode = psp.ModeReplace

			res, _, err := pushOnce(t, a, in)
			if err != nil {
				t.Fatal(err)
			}
			sent := node.sent()
			if len(sent) != 1 {
				t.Fatalf("the node was sent %d requests, want one", len(sent))
			}
			want := append([]string{cmdEnable, cmdSession + sessionName(sent[0]), cmdRollbackClean, cmdCopyStartup}, bootstrapLines()...)
			want = append(append(want, eapiLines()...), cmdSessionDiff, cmdCommit)
			if !reflect.DeepEqual(sent[0], want) {
				t.Errorf("node was sent %q,\nwant %q", sent[0], want)
			}
			// The diff command has no JSON model: under json the whole request fails with
			// 1003 and leaves its session pending.
			if got := node.sentFormats(); !reflect.DeepEqual(got, []string{eapiFormatText}) {
				t.Errorf("formats = %q, want [text] under replace", got)
			}
			if res.Diff != c.diff {
				t.Errorf("result diff = %q, want the diff entry's output %q", res.Diff, c.diff)
			}
			if !strings.Contains(log.String(), fmt.Sprintf("diff_bytes=%d", len(c.diff))) {
				t.Errorf("the log does not name the diff's length:\n%s", log.String())
			}
			for _, line := range []string{"+interface Ethernet1", "+++ session:", "--- system:"} {
				if strings.Contains(log.String(), line) {
					t.Errorf("the log carries the diff's %q:\n%s", line, log.String())
				}
			}
			noContent(t, "the push's log", log.String())
		})
	}
}

// A replace the node refuses is push.refused at the artifact's own line, re-based through
// the replace's longer list, and its session is aborted before the next attempt, as M7
// does: the abort is M7's request, answered as JSON.
func TestPushEAPIReplaceRefusedIsAborted(t *testing.T) {
	const reason = "Invalid input (at token 0: 'frobnicate')"
	// enable, the session, the reset's two, the bootstrap's two sent lines, then the
	// artifact's seven: command 13 is the artifact's last, its file line 8.
	node := &eapiNode{answer: eapiFailedAt(13, reason)}
	a, in, log := eapiSetup(t, node, psp.BootstrapViaPush)
	in.Push.Mode = psp.ModeReplace

	_, _, err := pushOnce(t, a, in)
	f := stepFailure(t, err, findings.RulePushRefused)
	want := fmt.Sprintf("node n1 refused artifact device-config (checksum %s) at line 8: %s", in.Checksum, reason)
	if f.Message != want {
		t.Errorf("finding message = %q,\nwant %q", f.Message, want)
	}
	for _, line := range []string{"insert /", "delete /", "update /", "replace /", "+interface"} {
		if strings.Contains(f.Message, line) {
			t.Errorf("the refusal carries %q: %s", line, f.Message)
		}
	}
	noContent(t, "the refusal", f.Message, err.Error(), log.String())
	sent := node.sent()
	if len(sent) != 2 || !reflect.DeepEqual(sent[1], []string{cmdEnable, cmdSession + sessionName(sent[0]), cmdAbort}) {
		t.Fatalf("the node was sent %q, want the push and its session aborted", sent)
	}
	if got := node.sentFormats(); !reflect.DeepEqual(got, []string{eapiFormatText, eapiFormatJSON}) {
		t.Errorf("formats = %q, want the replace as text and the abort as M7's json", got)
	}
}

// A line the node will not run is push.refused, final, naming the node, the artifact, its
// checksum, the artifact's own line and the node's reason — and none of the command the
// node echoed. The line is re-based through the command list, so the dropped empty line
// is counted: the node's command 9 is the file's line 8.
func TestPushEAPIRefusedArtifactLine(t *testing.T) {
	const reason = "Invalid input (at token 0: 'frobnicate')"
	node := &eapiNode{answer: eapiFailedAt(9, reason)}
	a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)

	_, _, err := pushOnce(t, a, in)
	f := stepFailure(t, err, findings.RulePushRefused)
	want := fmt.Sprintf("node n1 refused artifact device-config (checksum %s) at line 8: %s", in.Checksum, reason)
	if f.Message != want || f.Step != findings.StepPush || f.Object != "n1" {
		t.Errorf("finding = %+v\nwant message %q at step push on n1", f, want)
	}
	noContent(t, "the refusal", f.Message, err.Error(), log.String())
	// The node's message echoed the command it refused, and its errors echo a token of
	// it; the refusal keeps the reason and drops the echo (Constitution X).
	for _, c := range eapiLines() {
		if strings.Contains(f.Message, c) {
			t.Errorf("the refusal carries the echoed command %q: %s", c, f.Message)
		}
	}
	// Nothing landed, so the session the attempt named is aborted, best effort.
	sent := node.sent()
	if len(sent) != 2 {
		t.Fatalf("the node was sent %d requests, want the push and the abort", len(sent))
	}
	session := sessionName(sent[0])
	if !reflect.DeepEqual(sent[1], []string{cmdEnable, cmdSession + session, cmdAbort}) {
		t.Errorf("the second request was %q, want the refused session aborted", sent[1])
	}
	if !strings.Contains(log.String(), "aborted") || !strings.Contains(log.String(), session) {
		t.Errorf("the log does not say the session was aborted:\n%s", log.String())
	}
}

// An abort that outlasts the push's budget leaves the refusal a refusal: push.refused,
// final, as the node worded it, never a push.failed that is retried. The abort is M7's
// courtesy and cannot fail the run; the dispatch tells a refusal before the budget
// (M11 D-034, which asks the json_rpc arm's reason in a request of its own the same way).
func TestPushEAPIRefusalOutlastsItsAbort(t *testing.T) {
	const reason = "Invalid input (at token 0: 'frobnicate')"
	refuse := eapiFailedAt(9, reason)
	node := &eapiNode{answer: func(w http.ResponseWriter, r *http.Request, cmds []string) {
		if len(cmds) > 0 && cmds[len(cmds)-1] == cmdAbort {
			select {
			case <-r.Context().Done():
			case <-time.After(10 * time.Second):
			}
			return
		}
		refuse(w, r, cmds)
	}}
	a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
	in.Push.TimeoutS = 1

	_, _, err := pushOnce(t, a, in)
	f := stepFailure(t, err, findings.RulePushRefused)
	if want := fmt.Sprintf("node n1 refused artifact device-config (checksum %s) at line 8: %s", in.Checksum, reason); f.Message != want {
		t.Errorf("finding message = %q,\nwant %q", f.Message, want)
	}
	if !strings.Contains(log.String(), "could not be aborted") {
		t.Errorf("the log does not say the abort failed:\n%s", log.String())
	}
	noContent(t, "the refusal", f.Message, err.Error(), log.String())
}

