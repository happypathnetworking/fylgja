// The transport's failures are M5's shapes, worded for this mechanism's endpoint: a status
// that is not 2xx, a login refused with the variables named, a body that is not an answer,
// a body longer than the limit, and a node that does not answer within the budget. Each is
// push.failed and retried, and none quotes the node's body.
func TestPushEAPITransportFailures(t *testing.T) {
	t.Run("401", func(t *testing.T) {
		node := &eapiNode{answer: func(w http.ResponseWriter, _ *http.Request, _ []string) {
			http.Error(w, "Unauthorized", http.StatusUnauthorized)
		}}
		a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
		_, _, err := pushOnce(t, a, in)
		f := retryableFailure(t, err)
		if !strings.Contains(f.Message, "401") || !strings.Contains(f.Message, "FYLGJA_EOS_USERNAME/FYLGJA_EOS_PASSWORD") ||
			!strings.Contains(f.Message, eapiPath) {
			t.Errorf("finding = %+v, want the status, the endpoint and the login's variable names", f)
		}
		noContent(t, "a 401", f.Message, err.Error(), log.String())
	})
	t.Run("500", func(t *testing.T) {
		node := &eapiNode{answer: func(w http.ResponseWriter, _ *http.Request, cmds []string) {
			http.Error(w, strings.Join(cmds, "\n"), http.StatusInternalServerError)
		}}
		a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
		_, _, err := pushOnce(t, a, in)
		f := retryableFailure(t, err)
		if !strings.Contains(f.Message, "500") {
			t.Errorf("finding = %+v, want the status", f)
		}
		noContent(t, "a 500", f.Message, err.Error(), log.String())
	})
	t.Run("a body that is not an answer", func(t *testing.T) {
		node := &eapiNode{answer: func(w http.ResponseWriter, _ *http.Request, cmds []string) {
			_, _ = w.Write([]byte("not JSON at all: " + strings.Join(cmds, "\n")))
		}}
		a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
		_, _, err := pushOnce(t, a, in)
		f := retryableFailure(t, err)
		if !strings.Contains(f.Message, "a body that is not a JSON-RPC answer") {
			t.Errorf("finding = %+v, want the body named and not quoted", f)
		}
		noContent(t, "an unreadable body", f.Message, err.Error(), log.String())
	})
	t.Run("an answer longer than the limit", func(t *testing.T) {
		// Cut at jsonRPCAnswerLimit, the answer no longer parses: reported as a body that
		// is not an answer and retried, never searched for a refusal.
		node := &eapiNode{answer: func(w http.ResponseWriter, _ *http.Request, _ []string) {
			_, _ = w.Write([]byte(`{"jsonrpc":"2.0","id":1,"result":[{"output":"`))
			_, _ = w.Write(bytes.Repeat([]byte("x"), jsonRPCAnswerLimit))
			_, _ = w.Write([]byte(`"}]}`))
		}}
		a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
		_, _, err := pushOnce(t, a, in)
		f := retryableFailure(t, err)
		if !strings.Contains(f.Message, "a body that is not a JSON-RPC answer") {
			t.Errorf("finding = %+v, want the cut answer named", f)
		}
		noContent(t, "a cut answer", f.Message, err.Error(), log.String())
	})
	t.Run("no result and no error", func(t *testing.T) {
		node := &eapiNode{answer: func(w http.ResponseWriter, _ *http.Request, _ []string) {
			_, _ = w.Write([]byte(`{"jsonrpc":"2.0","id":1}`))
		}}
		a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
		_, _, err := pushOnce(t, a, in)
		f := retryableFailure(t, err)
		if !strings.Contains(f.Message, "neither a result nor an error") {
			t.Errorf("finding = %+v, want the empty answer named", f)
		}
		noContent(t, "an empty answer", f.Message, err.Error(), log.String())
	})
	t.Run("the budget", func(t *testing.T) {
		node := &eapiNode{answer: func(_ http.ResponseWriter, r *http.Request, _ []string) {
			select {
			case <-r.Context().Done():
			case <-time.After(10 * time.Second):
			}
		}}
		a, in, _ := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
		in.Push.TimeoutS = 1
		start := time.Now()
		_, _, err := pushOnce(t, a, in)
		if took := time.Since(start); took > 5*time.Second {
			t.Errorf("the push took %s against a 1s budget", took)
		}
		f := retryableFailure(t, err)
		if !strings.Contains(f.Message, "within 1s (push_timeout_s)") || !strings.Contains(f.Message, eapiPath) {
			t.Errorf("finding = %+v, want the endpoint and the budget named", f)
		}
	})
	t.Run("a node that cannot be reached", func(t *testing.T) {
		a, in, log := eapiSetup(t, &eapiNode{answer: eapiRan}, psp.BootstrapViaStartupConfig)
		l, err := net.Listen("tcp", "127.0.0.1:0")
		if err != nil {
			t.Fatal(err)
		}
		in.Push.Port = l.Addr().(*net.TCPAddr).Port
		_ = l.Close() // nothing listens there now
		_, _, err = pushOnce(t, a, in)
		f := retryableFailure(t, err)
		if !strings.Contains(f.Message, "connection refused") {
			t.Errorf("finding = %+v, want the transport's error", f)
		}
		noContent(t, "a transport failure", f.Message, err.Error(), log.String())
	})
	t.Run("a push login unset", func(t *testing.T) {
		node := &eapiNode{answer: eapiRan}
		a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
		a.Getenv = mapEnv(map[string]string{"FYLGJA_EOS_USERNAME": "admin"})
		_, _, err := pushOnce(t, a, in)
		f := stepFailure(t, err, findings.RulePushFailed)
		if !strings.Contains(f.Message, "FYLGJA_EOS_PASSWORD is unset") || len(node.sent()) != 0 {
			t.Errorf("finding %+v after %d requests, want the variable named and nothing sent", f, len(node.sent()))
		}
		noContent(t, "an unset login", f.Message, err.Error(), log.String())
	})
}

// A cancellation reaches an eAPI push as it reaches a JSON-RPC one: a cancellation the
// workflow asked for is a cancellation, and a heartbeat that never reached the workflow
// service is push.failed, naming the artifact, and retried.
func TestPushEAPICutShort(t *testing.T) {
	node := &eapiNode{answer: func(_ http.ResponseWriter, r *http.Request, _ []string) { <-r.Context().Done() }}
	a, in, _ := eapiSetup(t, node, psp.BootstrapViaStartupConfig)
	ctx, cancel := context.WithCancelCause(context.Background())
	time.AfterFunc(50*time.Millisecond, func() { cancel(temporal.NewCanceledError()) })

	_, err := a.PushConfig(ctx, in)
	var appErr *temporal.ApplicationError
	if !errors.Is(err, context.Canceled) || errors.As(err, &appErr) {
		t.Errorf("error %v, want the cancellation itself", err)
	}
}
