// eapiArtifact is a small artifact of the shape a CLI rendering has for this mechanism: a
// comment line, a host name, and two interface blocks with indented lines, the last of
// which the node will refuse. Its own line numbers are what a refusal must re-base onto:
// line 3 is empty and not sent, so the node counts one command fewer than the file has
// lines from there on.
const eapiArtifact = "! n1: " + pushMarker + "\n" +
	"hostname n1\n" +
	"\n" +
	"interface Ethernet1\n" +
	"   description to n2 Ethernet1\n" +
	"   no shutdown\n" +
	"interface Ethernet2\n" +
	"   frobnicate 1\n"

// eapiBootstrap is the bootstrap of a package whose bootstrap reaches the node through the
// push: the compiler's generated header, then the one line the package declares. Line 2 is
// empty and not sent, so its last line is its third and the node's second command of it.
const eapiBootstrap = "! generated by fylgja\n" +
	"\n" +
	"hostname n1\n"

// eapiLines and bootstrapLines are those files' lines as they are sent: comments kept,
// empty dropped.
func eapiLines() []string      { return texts(configCommands([]byte(eapiArtifact), false)) }
func bootstrapLines() []string { return texts(configCommands([]byte(eapiBootstrap), true)) }

// eapiPush is a package's push as this mechanism takes it: the command API over HTTPS
// with a login of its own, an explicit commit, merge. Every value is
// the package's data; the code under test reads it and names no platform.
func eapiPush() wire.PushSpec {
	return wire.PushSpec{
		Delivery: DeliveryEAPI, Mode: "merge", Commit: "explicit", Scheme: "https", Port: 443,
		UsernameEnv: "FYLGJA_EOS_USERNAME", PasswordEnv: "FYLGJA_EOS_PASSWORD", TimeoutS: 30,
	}
}

// eapiNode is a fake command-API endpoint: it keeps each request it is sent and the
// answer format it asked for, refusing anything that is not a runCmds call in one of the
// two formats the mechanism sends, and answers with answer.
type eapiNode struct {
	answer func(w http.ResponseWriter, r *http.Request, cmds []string)

	mu       sync.Mutex
	commands [][]string
	formats  []string
	logins   []string
}

func (n *eapiNode) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	var req eapiCall
	if r.URL.Path != eapiPath || r.Method != http.MethodPost || json.NewDecoder(r.Body).Decode(&req) != nil ||
		req.Method != "runCmds" || req.JSONRPC != "2.0" || req.Params.Version != 1 ||
		(req.Params.Format != eapiFormatJSON && req.Params.Format != eapiFormatText) {
		http.Error(w, "not a runCmds request", http.StatusBadRequest)
		return
	}
	u, p, _ := r.BasicAuth()
	n.mu.Lock()
	n.commands = append(n.commands, req.Params.Commands)
	n.formats = append(n.formats, req.Params.Format)
	n.logins = append(n.logins, u+":"+p)
	n.mu.Unlock()
	n.answer(w, r, req.Params.Commands)
}

// sentFormats returns the answer format each request asked for, in order.
func (n *eapiNode) sentFormats() []string {
	n.mu.Lock()
	defer n.mu.Unlock()
	return append([]string(nil), n.formats...)
}

// sent returns the requests the node was sent so far.
func (n *eapiNode) sent() [][]string {
	n.mu.Lock()
	defer n.mu.Unlock()
	out := make([][]string, len(n.commands))
	copy(out, n.commands)
	return out
}

// eapiRan answers as a node that ran every command: one result entry each, nothing to say.
func eapiRan(w http.ResponseWriter, _ *http.Request, cmds []string) {
	eapiRanWithWarnings()(w, nil, cmds)
}

// eapiRanWithWarnings answers success with a warning on each of the given 1-based command
// indices, as cEOS 4.32.0.2F answers a configuration naming an interface it lacks.
func eapiRanWithWarnings(at ...int) func(http.ResponseWriter, *http.Request, []string) {
	return func(w http.ResponseWriter, _ *http.Request, cmds []string) {
		result := make([]map[string]any, len(cmds))
		for i := range result {
			result[i] = map[string]any{}
		}
		for _, n := range at {
			result[n-1] = map[string]any{"warnings": []string{
				"Interface does not exist. The configuration will not take effect until the module is inserted."}}
		}
		_ = json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "result": result})
	}
}

// eapiFailedAt answers as cEOS 4.32.0.2F answers a command it will not run: HTTP
// 200, a JSON-RPC error whose message echoes the command and whose data holds one entry
// per command run, the last carrying the reason.
func eapiFailedAt(nth int, reasons ...string) func(http.ResponseWriter, *http.Request, []string) {
	return func(w http.ResponseWriter, r *http.Request, cmds []string) {
		// A shorter list than the push's is the abort that follows a refusal, which this
		// node runs: only the push itself has a command the node will not run.
		if nth > len(cmds) {
			eapiRan(w, r, cmds)
			return
		}
		data := make([]map[string]any, nth)
		for i := range data {
			data[i] = map[string]any{}
		}
		data[nth-1] = map[string]any{"errors": reasons}
		_ = json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "error": map[string]any{
			"code":    1002,
			"message": fmt.Sprintf("CLI command %d of %d '%s' failed: invalid command", nth, len(cmds), cmds[nth-1]),
			"data":    data,
		}})
	}
}

// eapiSetup stages eapiArtifact and eapiBootstrap as n1's under a fresh state root, with
// the bootstrap applied via, and serves node over TLS.
func eapiSetup(t *testing.T, node http.Handler, via string) (*Activities, wire.PushInput, *bytes.Buffer) {
	t.Helper()
	a := testActivities(t, &fakeRunner{})
	a.Getenv = mapEnv(map[string]string{"FYLGJA_EOS_USERNAME": "admin", "FYLGJA_EOS_PASSWORD": pushPassword})
	var log bytes.Buffer
	a.Log = slog.New(slog.NewTextHandler(&log, &slog.HandlerOptions{Level: slog.LevelDebug}))

	checksum := stagePush(t, a, stagedBundle{artifact: eapiArtifact, bootstrap: eapiBootstrap, via: via})
	host, port := pushNodeAt(t, node)
	push := eapiPush()
	push.Port = port
	return a, wire.PushInput{
		Node: "n1", MgmtIPv4: host, TwinDir: a.Paths.Twin, Artifact: "configs/n1.device-config",
		Checksum: checksum, Push: push,
	}, &log
}

// sessionName is the configuration session one request named, or "" if it named none.
func sessionName(cmds []string) string {
	for _, c := range cmds {
		if name, ok := strings.CutPrefix(c, cmdSession); ok {
			return name
		}
	}
	return ""
}

// The mechanism's own request: one POST of one command list, privileged mode first, a
// configuration session named for the attempt, the artifact's lines as they are with
// empty ones dropped, and the commit — under the package's login, and nothing that
// surfaces carrying the configuration or the password.
func TestPushEAPICommitsInOneRequest(t *testing.T) {
	node := &eapiNode{answer: eapiRan}
	a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)

	res, beats, err := pushOnce(t, a, in)
	if err != nil {
		t.Fatal(err)
	}
	sent := node.sent()
	if len(sent) != 1 {
		t.Fatalf("the node was sent %d requests, want one", len(sent))
	}
	session := sessionName(sent[0])
	want := append(append([]string{cmdEnable, cmdSession + session}, eapiLines()...), cmdCommit)
	if !reflect.DeepEqual(sent[0], want) {
		t.Errorf("node was sent %q,\nwant %q", sent[0], want)
	}
	// fylgja-<attempt>-<unix nanoseconds>: a committed name cannot be reused.
	if !strings.HasPrefix(session, eapiSessionPrefix+"1-") || len(session) <= len(eapiSessionPrefix)+2 {
		t.Errorf("session %q, want %s<attempt>-<unix ns>", session, eapiSessionPrefix)
	}
	if node.logins[0] != "admin:"+pushPassword {
		t.Errorf("login = %q, want the package's variables' values", node.logins[0])
	}
	// Under merge the request is M7's, answered as JSON, and asks for no diff.
	if got := node.sentFormats(); !reflect.DeepEqual(got, []string{eapiFormatJSON}) {
		t.Errorf("formats = %q, want [json] under merge", got)
	}
	if res.Node != "n1" || res.Checksum != in.Checksum || res.Size != len(eapiArtifact) || res.PushedInS <= 0 || res.Diff != "" {
		t.Errorf("result = %+v, want n1 with the checksum, %d bytes, a duration and no diff", res, len(eapiArtifact))
	}
	if beats < 1 {
		t.Error("the push sent no heartbeat before its request")
	}

	b, err := json.Marshal(struct {
		In  wire.PushInput
		Res wire.PushResult
	}{in, res})
	if err != nil {
		t.Fatal(err)
	}
	noContent(t, "the push's input and result", string(b))
	noContent(t, "the push's log", log.String())
	// The by_hand line names the login by its variables and the file by its staged path.
	for _, want := range []string{"pushed", "delivery=" + DeliveryEAPI, "artifact=device-config",
		"checksum=" + in.Checksum, `$FYLGJA_EOS_USERNAME:$FYLGJA_EOS_PASSWORD`, eapiPath, `configure session by-hand`} {
		if !strings.Contains(log.String(), want) {
			t.Errorf("log does not say %q:\n%s", want, log.String())
		}
	}
}

