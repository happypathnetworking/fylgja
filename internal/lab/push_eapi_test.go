// A framing command the node will not run is the mechanism's own failure, not the
// configuration's: push.failed, retried, and the next attempt names a session no commit
// has taken.
func TestPushEAPIFramingFailureIsRetried(t *testing.T) {
	const reason = "Cannot enter session (already completed)"
	node := &eapiNode{answer: eapiFailedAt(2, reason)}
	a, in, log := eapiSetup(t, node, psp.BootstrapViaStartupConfig)

	_, _, err := pushOnce(t, a, in)
	f := retryableFailure(t, err)
	if !strings.Contains(f.Message, "the framing command `"+cmdSession) || !strings.Contains(f.Message, "failed: "+reason) {
		t.Errorf("finding = %+v, want the framing command and the node's reason", f)
	}
	noContent(t, "a framing failure", f.Message, err.Error(), log.String())

	// The same input again: a fresh session name, so a name a commit took cannot block
	// the retry for ever.
	if _, _, err := pushOnce(t, a, in); err == nil {
		t.Fatal("the second attempt succeeded against a node that refuses its session")
	}
	sent := node.sent()
	first, second := sessionName(sent[0]), sessionName(sent[len(sent)-1])
	if first == "" || first == second {
		t.Errorf("attempts named sessions %q and %q, want a fresh name per attempt", first, second)
	}
}

