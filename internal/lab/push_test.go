// cutInsideEcho answers as SR Linux 24.7.1 answered a refused replace: a JSON-RPC error
// whose message the node cut at about 1 KiB, inside its echo of the
// commands, ending "...". Neither the marker that ends the echo nor the reason arrives.
// The echo here is shorter than the node's cap, so it is cut at two thirds of its length,
// which leaves the artifact's first line, and the test marker, inside what is sent.
func cutInsideEcho(w http.ResponseWriter, _ *http.Request, commands []string) {
	msg := "Error: Cli commands '" + strings.Join(commands, "\n")
	msg = msg[:len(msg)*2/3] + "..."
	_ = json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "error": map[string]any{"code": -1, "message": msg}})
}

// validateCommands is the request a refused replace whose reason was cut is asked again
// with (D-034): it enters the private candidate the refusal left and validates it.
var validateCommands = []string{cmdEnterCandidate, cmdCommitValidate}

// askedAgain answers the replace with first and the request that asks again with second.
func askedAgain(first, second func(http.ResponseWriter, *http.Request, []string)) func(http.ResponseWriter, *http.Request, []string) {
	return func(w http.ResponseWriter, r *http.Request, commands []string) {
		if reflect.DeepEqual(commands, validateCommands) {
			second(w, r, commands)
			return
		}
		first(w, r, commands)
	}
}

