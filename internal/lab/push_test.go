// pushMarker stands in for the configuration's own bytes: it must reach the node and
// nothing else — no finding, result, input or log line.
const pushMarker = "PUSH-TEST-MARKER"

// pushPassword is the login's value in these tests; like the marker, it reaches only the
// node's Authorization header.
const pushPassword = "push-test-password"

// pushArtifact is a small SR Linux artifact: a comment, an empty line (dropped), and a
// line SR Linux refuses, at line 10 of the file. The node counts
// commands, not file lines: `enter candidate private` is its line 1 and the empty line is
// not sent, so the refused line is the node's line 10 too, where without the empty line it
// would be 11: the node's line N is the file's line N−1.
const pushArtifact = "# n1: " + pushMarker + "\n" +
	"set / system name host-name n1\n" +
	"\n" +
	"set / interface ethernet-1/1 admin-state enable\n" +
	"set / interface ethernet-1/1 description \"to n2 ethernet-1/1\"\n" +
	"set / interface ethernet-1/1 subinterface 0 admin-state enable\n" +
	"set / interface ethernet-1/2 admin-state enable\n" +
	"set / interface ethernet-1/2 description \"to n3 ethernet-1/1\"\n" +
	"set / interface ethernet-1/2 subinterface 0 admin-state enable\n" +
	"set / interface e1-2 admin-state enable\n"

// pushNode is a fake SR Linux JSON-RPC endpoint: it keeps each request it is sent and
// answers with answer.
type pushNode struct {
	answer func(w http.ResponseWriter, r *http.Request, commands []string)

	mu       sync.Mutex
	commands [][]string
	logins   []string
}

func (n *pushNode) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	var req jsonRPCRequest
	if r.URL.Path != "/jsonrpc" || r.Method != http.MethodPost || json.NewDecoder(r.Body).Decode(&req) != nil ||
		req.Method != "cli" || req.JSONRPC != "2.0" {
		http.Error(w, "not a JSON-RPC cli request", http.StatusBadRequest)
		return
	}
	u, p, _ := r.BasicAuth()
	n.mu.Lock()
	n.commands = append(n.commands, req.Params.Commands)
	n.logins = append(n.logins, u+":"+p)
	n.mu.Unlock()
	n.answer(w, r, req.Params.Commands)
}

func committed(w http.ResponseWriter, _ *http.Request, _ []string) {
	_, _ = io.WriteString(w, `{"jsonrpc":"2.0","id":1,"result":[{"text":"All changes have been committed. Leaving candidate mode.\n"}]}`)
}

// refusing answers as SR Linux answers a bad artifact: HTTP 200, a JSON-RPC error
// echoing every command before the node's reason.
func refusing(line int, reason string) func(http.ResponseWriter, *http.Request, []string) {
	return func(w http.ResponseWriter, _ *http.Request, commands []string) {
		msg := fmt.Sprintf("Error: Cli commands '%s' failed with error 1: At line %d: Error: %s",
			strings.Join(commands, "\n"), line, reason)
		_ = json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "error": map[string]any{"code": -1, "message": msg}})
	}
}

// pushBootstrap is n1's bootstrap as the compiler renders one: a generated header, then
// the package's lines. Its own line numbers, so a refusal of one of them can be told from
// a refusal of the artifact's.
const pushBootstrap = "# generated by fylgja\n" +
	"\n" +
	"set / system name host-name n1\n" +
	"set / interface ethernet-1/1 admin-state enable\n"

// stagedBundle is the bundle one push reads, as the compiler wrote it and StageBundle
// copied it: a configuration artifact, a bootstrap, and how the bootstrap reaches the
// node. "startup_config" is M5's default and the shipped SR Linux package's, under which
// the bootstrap is the lab tool's business and the push sends the artifact alone; "push"
// is M7's, under which the push sends both.
type stagedBundle struct {
	artifact  string
	bootstrap string
	via       string
}

// stagePush writes that bundle under the activities' state root and returns the
// artifact's checksum, as the manifest records it.
func stagePush(t *testing.T, a *Activities, b stagedBundle) string {
	t.Helper()
	bundleDir := filepath.Join(a.Paths.Twin, "bundle")
	if err := os.MkdirAll(filepath.Join(bundleDir, "configs"), 0o755); err != nil {
		t.Fatal(err)
	}
	for name, content := range map[string]string{"n1.device-config": b.artifact, "n1.cli": b.bootstrap} {
		if err := os.WriteFile(filepath.Join(bundleDir, "configs", name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	sum := md5.Sum([]byte(b.artifact))
	checksum := hex.EncodeToString(sum[:])
	manifest := compiler.Manifest{
		BundleVersion: "3",
		Nodes: []compiler.ManifestNode{{
			Name: "n1", Platform: "testos", PSP: compiler.ManifestPSP{ID: "testos", Source: "embedded"},
			Artifact: &compiler.ManifestArtifact{
				Name: "device-config", ContentType: "text/plain", Checksum: checksum,
				Size: len(b.artifact), File: "configs/n1.device-config",
			},
			Bootstrap: compiler.ManifestBootstrap{File: "configs/n1.cli", Via: b.via},
		}},
	}
	raw, err := json.Marshal(manifest)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(bundleDir, compiler.ManifestFile), raw, 0o644); err != nil {
		t.Fatal(err)
	}
	return checksum
}

// pushNodeAt serves node over TLS and returns the host and port to reach it at, as a
// node's management address and its package's push port.
func pushNodeAt(t *testing.T, node http.Handler) (host string, port int) {
	t.Helper()
	srv := httptest.NewTLSServer(node)
	t.Cleanup(srv.Close)
	host, text, err := net.SplitHostPort(strings.TrimPrefix(srv.URL, "https://"))
	if err != nil {
		t.Fatal(err)
	}
	port, _ = strconv.Atoi(text)
	return host, port
}

// pushSetup stages pushArtifact as n1's under a fresh state root and serves node over TLS,
// returning the activities and the input that pushes it there.
func pushSetup(t *testing.T, node http.Handler) (*Activities, wire.PushInput, *bytes.Buffer) {
	t.Helper()
	a := testActivities(t, &fakeRunner{})
	a.Getenv = mapEnv(map[string]string{"FYLGJA_SRLINUX_USERNAME": "admin", "FYLGJA_SRLINUX_PASSWORD": pushPassword})
	var log bytes.Buffer
	a.Log = slog.New(slog.NewTextHandler(&log, &slog.HandlerOptions{Level: slog.LevelDebug}))

	checksum := stagePush(t, a, stagedBundle{artifact: pushArtifact, bootstrap: pushBootstrap, via: psp.BootstrapViaStartupConfig})
	host, port := pushNodeAt(t, node)
	push := srlinuxPush()
	push.Port = port
	return a, wire.PushInput{
		Node: "n1", MgmtIPv4: host, TwinDir: a.Paths.Twin, Artifact: "configs/n1.device-config",
		Checksum: checksum, Push: push,
	}, &log
}

// pushOnce runs PushConfig as the worker does, under the activity test environment, and
// counts its heartbeats.
func pushOnce(t *testing.T, a *Activities, in wire.PushInput) (wire.PushResult, int, error) {
	t.Helper()
	env := activityEnv(a.PushConfig, wire.ActPushConfig)
	var mu sync.Mutex
	beats := 0
	env.SetOnActivityHeartbeatListener(func(_ *activity.Info, _ converter.EncodedValues) {
		mu.Lock()
		beats++
		mu.Unlock()
	})
	val, err := env.ExecuteActivity(wire.ActPushConfig, in)
	mu.Lock()
	defer mu.Unlock()
	if err != nil {
		return wire.PushResult{}, beats, err
	}
	var res wire.PushResult
	if err := val.Get(&res); err != nil {
		t.Fatal(err)
	}
	return res, beats, nil
}

// artifactLines are pushArtifact's lines as they are sent: comments kept, empty dropped.
func artifactLines() []string {
	var out []string
	for _, l := range strings.Split(pushArtifact, "\n") {
		if l != "" {
			out = append(out, l)
		}
	}
	return out
}

// retryableFailure asserts err is a retryable push.failed and returns its finding.
func retryableFailure(t *testing.T, err error) findings.Finding {
	t.Helper()
	var appErr *temporal.ApplicationError
	if !errors.As(err, &appErr) || appErr.Type() != findings.RulePushFailed {
		t.Fatalf("error = %v, want an application error of type %s", err, findings.RulePushFailed)
	}
	if appErr.NonRetryable() {
		t.Errorf("%v is non-retryable; a push that could not be made is retried", err)
	}
	var f findings.Finding
	if err := appErr.Details(&f); err != nil {
		t.Fatal(err)
	}
	return f
}

// noContent fails if any of what surfaces carries the artifact's marker or the password.
func noContent(t *testing.T, what string, surfaces ...string) {
	t.Helper()
	for _, s := range surfaces {
		for _, secret := range []string{pushMarker, pushPassword} {
			if strings.Contains(s, secret) {
				t.Errorf("%s carries %q: %s", what, secret, s)
			}
		}
	}
}

// M5's push under merge: `enter candidate private`, the artifact's lines as they are with
// empty ones dropped, `commit now`, under the package's login, heartbeating before the
// request; the result names the checksum and size, and nothing that surfaces carries the
// content or the password. The shipped package is on
// replace from format 0.6 (TestPushConfigReplaceExplicit); a package on merge still
// creates.
func TestPushConfigMergeExplicit(t *testing.T) {
	node := &pushNode{answer: committed}
	a, in, log := pushSetup(t, node)
	in.Push.Mode = psp.ModeMerge

	res, beats, err := pushOnce(t, a, in)
	if err != nil {
		t.Fatal(err)
	}
	want := append(append([]string{"enter candidate private"}, artifactLines()...), "commit now")
	if len(node.commands) != 1 || !reflect.DeepEqual(node.commands[0], want) {
		t.Errorf("node was sent %q, want one request of %q", node.commands, want)
	}
	if node.logins[0] != "admin:"+pushPassword {
		t.Errorf("login = %q, want the package's variables' values", node.logins[0])
	}
	if res.Node != "n1" || res.Checksum != in.Checksum || res.Size != len(pushArtifact) || res.PushedInS <= 0 {
		t.Errorf("result = %+v, want n1 with the checksum, %d bytes and a duration", res, len(pushArtifact))
	}
	// A merge asks the node for no diff, so the result carries none, and its payload is
	// M5's byte for byte (diff is omitted when empty).
	if res.Diff != "" {
		t.Errorf("a merge's result carries a diff: %q", res.Diff)
	}
	if beats < 1 {
		t.Error("the push sent no heartbeat before its request")
	}

	b, err := json.Marshal(struct {
		In  wire.PushInput
		Res wire.PushResult
	}{in, res})
	if err != nil {
		t.Fatal(err)
	}
	noContent(t, "the push's input and result", string(b))
	noContent(t, "the push's log", log.String())
	for _, want := range []string{"pushed", "artifact=device-config", "checksum=" + in.Checksum,
		fmt.Sprintf("size=%d", len(pushArtifact)), `$FYLGJA_SRLINUX_USERNAME:$FYLGJA_SRLINUX_PASSWORD`} {
		if !strings.Contains(log.String(), want) {
			t.Errorf("log does not say %q:\n%s", want, log.String())
		}
	}
}

// Replace resets the candidate to the baseline, sends the bootstrap and the artifact, and
// asks for the diff before the commit; an implicit commit sends the
// lines alone. `delete /` is sent by no list (M5's replace, gone).
func TestPushConfigModes(t *testing.T) {
	replace := append([]string{"enter candidate private", "load startup"}, bootstrapCommands()...)
	replace = append(append(replace, artifactLines()...), "diff flat", "commit now")
	for _, c := range []struct {
		mode, commit string
		want         []string
	}{
		{"replace", "explicit", replace},
		{"merge", "implicit", artifactLines()},
	} {
		t.Run(c.mode+"/"+c.commit, func(t *testing.T) {
			node := &pushNode{answer: committed}
			a, in, _ := pushSetup(t, node)
			in.Push.Mode, in.Push.Commit = c.mode, c.commit
			if _, _, err := pushOnce(t, a, in); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(node.commands[0], c.want) {
				t.Errorf("node was sent %q, want %q", node.commands[0], c.want)
			}
			for _, cmd := range node.commands[0] {
				if cmd == "delete /" {
					t.Error("the list sends `delete /`, M5's replace, which took the probe node dark")
				}
			}
		})
	}
	t.Run("replace/implicit", func(t *testing.T) {
		node := &pushNode{answer: committed}
		a, in, _ := pushSetup(t, node)
		in.Push.Mode, in.Push.Commit = "replace", "implicit"
		_, _, err := pushOnce(t, a, in)
		f := stepFailure(t, err, findings.RulePushFailed)
		const want = "mode replace with commit implicit has no command list for delivery json_rpc: " +
			"the reset loads the baseline into a candidate and commits it, which an implicit commit has none of"
		if !strings.Contains(f.Message, want) || len(node.commands) != 0 {
			t.Errorf("finding %+v after %d requests, want %q before any request", f, len(node.commands), want)
		}
	})
}

// bootstrapCommands are pushBootstrap's lines as they are sent: comments kept, empty
// dropped.
func bootstrapCommands() []string { return texts(configCommands([]byte(pushBootstrap), true)) }

// replaceDiff is a node's answer to a replace as SR Linux 24.7.1 gives it: the load's
// line, then the device's diff, then the commit's sentence, in one text entry. Its
// `insert` lines are configuration, which nothing but the push's result may carry.
const replaceDiff = "/system/configuration/checkpoint[id=__startup__]:\n" +
	"    Loaded startup configuration\n" +
	"\n" +
	"insert / interface ethernet-1/1 description \"to n2 ethernet-1/1\"\n" +
	"insert / system name host-name n1\n" +
	"All changes have been committed. Leaving candidate mode.\n"

// committedWithDiff answers a replace as SR Linux does, with no output-format: one
// result entry holding every command's text output.
func committedWithDiff(w http.ResponseWriter, _ *http.Request, _ []string) {
	_ = json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "result": []map[string]string{{"text": replaceDiff}}})
}

// The push under replace, the shipped package's from format 0.6 (M11 D-033): one request of
// `enter candidate private`, `load
// startup`, the bootstrap's lines whatever bootstrap_via says, the
// artifact's, `diff flat` and `commit now`, with no output-format. The result carries the
// node's text output as the device's diff, and the log carries its length alone: no log
// line, finding or other field holds a line of it.
func TestPushConfigReplaceExplicit(t *testing.T) {
	for _, via := range []string{psp.BootstrapViaStartupConfig, psp.BootstrapViaPush} {
		t.Run(via, func(t *testing.T) {
			node := &pushNode{answer: committedWithDiff}
			a, in, log := pushSetup(t, node)
			stagePush(t, a, stagedBundle{artifact: pushArtifact, bootstrap: pushBootstrap, via: via})
			in.Push.Mode = psp.ModeReplace

			res, _, err := pushOnce(t, a, in)
			if err != nil {
				t.Fatal(err)
			}
			want := append([]string{cmdEnterCandidate, cmdLoadStartup}, bootstrapCommands()...)
			want = append(append(want, artifactLines()...), cmdDiffFlat, cmdCommitNow)
			if len(node.commands) != 1 || !reflect.DeepEqual(node.commands[0], want) {
				t.Errorf("node was sent %q,\nwant one request of %q", node.commands, want)
			}
			if res.Diff != replaceDiff {
				t.Errorf("result diff = %q, want the node's text output %q", res.Diff, replaceDiff)
			}
			if res.Node != "n1" || res.Checksum != in.Checksum || res.Size != len(pushArtifact) {
				t.Errorf("result = %+v, want n1 with the artifact's checksum and size", res)
			}

			// The diff is the result's alone: the log names its length, and no line of it.
			if !strings.Contains(log.String(), fmt.Sprintf("diff_bytes=%d", len(replaceDiff))) {
				t.Errorf("the log does not name the diff's length:\n%s", log.String())
			}
			for _, line := range []string{"insert / interface", "insert / system", "Loaded startup configuration"} {
				if strings.Contains(log.String(), line) {
					t.Errorf("the log carries the diff's %q:\n%s", line, log.String())
				}
			}
			noContent(t, "the push's log", log.String())
			// The by_hand line sends the replace, bootstrap file first; its
			// whole text is TestPushByHandFollowsTheMode's.
			files := []string{filepath.Join(a.Paths.Twin, "bundle", "configs", "n1.cli"),
				filepath.Join(a.Paths.Twin, "bundle", "configs", "n1.device-config")}
			for _, want := range []string{cmdLoadStartup, cmdDiffFlat, strings.Join(files, " ")} {
				if !strings.Contains(log.String(), want) {
					t.Errorf("the by_hand line does not carry %q:\n%s", want, log.String())
				}
			}
		})
	}
}

